package detect

import (
	"math"
	"sort"

	"github.com/samyukthasyamsundar/geo-sentinel/internal/geo"
	"github.com/samyukthasyamsundar/geo-sentinel/internal/trace"
)

// minStatPoints is the least data the statistical checks need before they will say anything.
// With fewer points a few identical readings are ordinary, so staying silent is the honest answer.
const minStatPoints = 20

// ---- Accuracy: reported accuracy that is too perfect or too constant ----

// Accuracy looks at the accuracy values devices report. Real GPS accuracy fluctuates as satellite
// geometry and the environment change; many spoofing tools write one fixed value (often 0 or 1) for
// every point. This is a WEAK signal: some devices genuinely report a constant, so findings are
// Low or Medium and never High.
type Accuracy struct{}

func (Accuracy) Name() string { return "accuracy" }

func (Accuracy) Run(t *trace.Trace) []Finding {
	var vals []float64
	var first *trace.Fix
	for i := range t.Fixes {
		if t.Fixes[i].HasAccuracy() {
			vals = append(vals, t.Fixes[i].AccuracyM)
			if first == nil {
				first = &t.Fixes[i]
			}
		}
	}
	if len(vals) < minStatPoints {
		return nil
	}
	var out []Finding
	mn, mx, sum := vals[0], vals[0], 0.0
	for _, v := range vals {
		mn, mx = math.Min(mn, v), math.Max(mx, v)
		sum += v
	}
	mean := sum / float64(len(vals))

	if mx < 1.0 {
		out = append(out, newFinding("accuracy", Medium, *first,
			"every one of %d fixes claims accuracy under 1 m (max %.2f m); consumer GPS does not achieve that", len(vals), mx))
	}
	if mx-mn == 0 {
		out = append(out, newFinding("accuracy", Low, *first,
			"all %d fixes report exactly the same accuracy (%.1f m); real receivers vary", len(vals), mean))
	}
	return out
}

// ---- Smoothness: a path too regular to be a person or vehicle ----

// Smoothness measures how much the heading and speed wobble. A synthetic path generated by
// interpolating between two points has constant speed and heading; a real one has jitter even
// when standing still. WEAK signal, reported as Low/Medium.
type Smoothness struct{}

func (Smoothness) Name() string { return "smoothness" }

func (Smoothness) Run(t *trace.Trace) []Finding {
	if len(t.Fixes) < minStatPoints {
		return nil
	}
	var speeds, headings []float64
	var moved int
	for i := 1; i < len(t.Fixes); i++ {
		prev, cur := t.Fixes[i-1], t.Fixes[i]
		dt := cur.Time.Sub(prev.Time).Seconds()
		if dt <= 0 {
			continue
		}
		d := geo.DistanceM(prev.Point, cur.Point)
		speeds = append(speeds, d/dt)
		if d > 3 { // heading is meaningless when the position barely changed
			headings = append(headings, geo.BearingDeg(prev.Point, cur.Point))
			moved++
		}
	}
	if len(speeds) < minStatPoints-1 {
		return nil
	}
	var out []Finding
	last := t.Fixes[len(t.Fixes)-1]

	// Speed: robust spread, so one odd interval (a glitch, or a short final step) cannot hide an
	// otherwise machine-regular series. MAD/median is the median absolute deviation as a fraction of
	// the median speed. Walking and driving typically exceed 0.1 even at a steady pace.
	med, mad := medianMAD(speeds)
	if med > 0.5 && mad/med < 0.005 {
		out = append(out, newFinding("smoothness", Medium, last,
			"speed is almost perfectly constant (median %.2f m/s, typical variation %.3f%%) across %d intervals; real movement fluctuates",
			med, 100*mad/med, len(speeds)))
	}
	mean, _ := meanStd(speeds)

	// Heading: circular standard deviation of the course over the moving intervals.
	if moved >= minStatPoints-1 {
		if cs := circularStdDeg(headings); cs < 0.2 {
			out = append(out, newFinding("smoothness", Low, last,
				"the heading is a dead-straight line (%.3f deg deviation) over %d moving intervals; real paths wander",
				cs, moved))
		}
	}

	// Stationary jitter: a real receiver standing still still drifts by metres.
	if mean < 0.2 && allIdentical(t) {
		out = append(out, newFinding("smoothness", Medium, last,
			"%d fixes at exactly the same coordinates: a stationary real receiver always drifts by metres", len(t.Fixes)))
	}
	return out
}

// medianMAD returns the median and the median absolute deviation of v (v is not modified).
func medianMAD(v []float64) (median, mad float64) {
	c := append([]float64(nil), v...)
	sort.Float64s(c)
	median = quantile(c, 0.5)
	dev := make([]float64, len(c))
	for i, x := range c {
		dev[i] = math.Abs(x - median)
	}
	sort.Float64s(dev)
	return median, quantile(dev, 0.5)
}

func quantile(sorted []float64, q float64) float64 {
	n := len(sorted)
	if n == 0 {
		return 0
	}
	if n%2 == 1 {
		return sorted[n/2]
	}
	return (sorted[n/2-1] + sorted[n/2]) / 2
}

func meanStd(v []float64) (mean, sd float64) {
	for _, x := range v {
		mean += x
	}
	mean /= float64(len(v))
	for _, x := range v {
		sd += (x - mean) * (x - mean)
	}
	return mean, math.Sqrt(sd / float64(len(v)))
}

// circularStdDeg is the circular standard deviation of angles in degrees (0 = all identical).
func circularStdDeg(deg []float64) float64 {
	var s, c float64
	for _, d := range deg {
		r := d * math.Pi / 180
		s += math.Sin(r)
		c += math.Cos(r)
	}
	n := float64(len(deg))
	R := math.Hypot(s/n, c/n)
	if R >= 1 {
		return 0
	}
	return math.Sqrt(-2*math.Log(R)) * 180 / math.Pi
}

func allIdentical(t *trace.Trace) bool {
	for _, f := range t.Fixes[1:] {
		if f.Lat != t.Fixes[0].Lat || f.Lon != t.Fixes[0].Lon {
			return false
		}
	}
	return true
}
